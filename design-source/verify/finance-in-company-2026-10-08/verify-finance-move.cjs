const { chromium } = require('playwright')
const B = 'http://localhost:3011', O = process.argv[2]
const settle = (p, ms = 900) => p.waitForTimeout(ms)
;(async () => {
  const br = await chromium.launch()
  const d = await br.newContext({ viewport: { width: 1440, height: 1024 } })
  const p = await d.newPage()
  await p.goto(B + '/company/finance', { waitUntil: 'networkidle' }); await settle(p, 1500)
  console.log('landed', p.url())
  const railFinance = await p.locator('nav a[href="/finance"], nav a[href="/company/finance"]').count()
  console.log('rail finance links', railFinance)
  const railLabels = await p.locator('nav').first().locator('a[aria-label], button[aria-label]').evaluateAll((els) => els.map((e) => e.getAttribute('aria-label')))
  console.log('rail', railLabels.join(' | '))
  await p.screenshot({ path: `${O}/1440-finance-overview.png` })
  await p.getByRole('button', { name: /^Company/ }).first().click(); await settle(p, 700)
  await p.screenshot({ path: `${O}/1440-company-panel.png` })
  const row = p.getByRole('menuitem', { name: /^Finance/ })
  console.log('panel row', JSON.stringify(await row.innerText()), await row.getAttribute('aria-current'))
  await p.keyboard.press('Escape'); await settle(p, 300)
  await p.goto(B + '/company/finance/purchase-orders', { waitUntil: 'networkidle' }); await settle(p, 1200)
  await p.screenshot({ path: `${O}/1440-finance-pos.png` })
  // G F from Leads
  await p.goto(B + '/leads', { waitUntil: 'networkidle' }); await settle(p, 1200)
  await p.keyboard.press('g'); await p.keyboard.press('f'); await p.waitForURL(/company\/finance/, { timeout: 8000 }).catch(() => {})
  console.log('G F ->', p.url())
  const m = await br.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 })
  const q = await m.newPage()
  await q.goto(B + '/leads', { waitUntil: 'networkidle' }); await settle(q, 1500)
  await q.getByRole('button', { name: /^More/ }).first().click(); await settle(q, 800)
  await q.screenshot({ path: `${O}/390-more-sheet.png` })
  const more = await q.getByRole('dialog', { name: 'More' }).innerText().catch(() => '')
  console.log('more sheet', more.replace(/\n+/g, ' | '))
  await q.getByRole('dialog', { name: 'More' }).getByRole('button', { name: /^Company/ }).click(); await settle(q, 800)
  await q.screenshot({ path: `${O}/390-company-sheet.png` })
  await q.getByRole('menuitem', { name: /^Finance/ }).click(); await q.waitForURL(/company\/finance/, { timeout: 10000 }).catch(() => {}); await settle(q, 1800)
  console.log('phone landed', q.url())
  await q.screenshot({ path: `${O}/390-finance.png` })
  const sw = await q.evaluate(() => document.documentElement.scrollWidth)
  console.log('390 scrollWidth', sw)
  await br.close()
})().catch((e) => { console.error(e); process.exit(1) })
