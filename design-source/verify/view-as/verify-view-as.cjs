// REG-667 · Demo Studio › View as — probe against :3011 on the scratch test.db
const { chromium } = require('playwright')
const { execSync } = require('child_process')
const S = '/private/tmp/claude-501/-Users-vicky-Documents-GitHub-openmaison-prototype/3d178797-9f6d-4654-9be0-22448502c3dc/scratchpad'
const DB = `${S}/test.db`
const OUT = `${S}/shots`
const BASE = 'http://localhost:3011'
const q = (sql) => execSync(`sqlite3 "${DB}" "${sql.replace(/"/g, '\\"')}"`).toString().trim()
let pass = 0, fail = 0
const ok = (c, m) => { if (c) { pass++; console.log('  ok  ', m) } else { fail++; console.log('  FAIL', m) } }

;(async () => {
  execSync(`mkdir -p ${OUT}`)
  q(`INSERT OR REPLACE INTO settings (key, value, updated_at) VALUES ('lead_visibility', '"assigned"', strftime('%s','now'))`)
  q(`UPDATE members SET is_you = (id = 'dane')`)
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1440, height: 1024 } })
  const rows = async () => { await page.locator('[role="row"]').nth(1).waitFor({ timeout: 15000 }); return (await page.locator('[role="row"]').count()) - 1 }

  console.log('Dane (Owner)')
  await page.goto(`${BASE}/leads`, { waitUntil: 'networkidle' })
  const daneRows = await rows()
  ok(daneRows === Number(q(`SELECT count(*) FROM leads WHERE deleted_at IS NULL`)), `Dane sees ${daneRows} leads (every live lead)`)
  const block = page.getByRole('button', { name: /^Demo Studio/ })
  ok(await block.isVisible(), 'the Demo Studio block is a button')
  ok((await block.innerText()).includes('Dane Bruce Lee'), 'second line reads Dane Bruce Lee')
  await page.screenshot({ path: `${OUT}/va-01-rail-dane.png`, clip: { x: 0, y: 824, width: 360, height: 200 } })
  await block.click()
  const menu = page.getByRole('menu', { name: 'View as' })
  await menu.waitFor()
  const items = menu.getByRole('menuitemradio')
  ok((await items.count()) === 7, `menu lists ${await items.count()} members (7 expected, Hui Min included)`)
  ok(await menu.getByText('Demo only').isVisible(), 'Demo only pill')
  ok((await items.filter({ hasText: 'Dane' }).getAttribute('aria-checked')) === 'true', 'Dane is ticked')
  ok(await items.filter({ hasText: 'Hui Min' }).getByText('Admin', { exact: true }).isVisible(), 'Hui Min · Admin')
  ok(await items.filter({ hasText: 'Sarah' }).getByText('Designer · reports to James').isVisible(), 'Sarah · Designer · reports to James')
  await page.screenshot({ path: `${OUT}/va-02-menu.png` })

  console.log('View as Sarah (Designer)')
  await items.filter({ hasText: 'Sarah' }).click()
  await page.getByText('Viewing as Sarah · Designer').waitFor({ timeout: 10000 })
  ok(true, 'snackbar: Viewing as Sarah · Designer')
  ok(await page.getByRole('button', { name: 'Back to Dane' }).isVisible(), 'snackbar offers Back to Dane')
  ok(q(`SELECT id FROM members WHERE is_you = 1`) === 'sarah', 'the flag moved to Sarah')
  await page.waitForTimeout(1500)
  ok((await block.innerText()).includes('Viewing as Sarah'), 'second line reads Viewing as Sarah')
  await page.screenshot({ path: `${OUT}/va-03-sarah-leads.png` })
  await page.goto(`${BASE}/leads`, { waitUntil: 'networkidle' })
  const sarahRows = await rows()
  const expected = Number(q(`SELECT count(DISTINCT l.id) FROM leads l JOIN lead_assignees a ON a.lead_id = l.id WHERE l.deleted_at IS NULL AND a.member_id = 'sarah'`))
  ok(sarahRows === expected, `Sarah sees ${sarahRows} leads (her own: ${expected})`)
  await page.goto(`${BASE}/settings`, { waitUntil: 'networkidle' })
  await page.screenshot({ path: `${OUT}/va-04-sarah-settings.png` })

  console.log('A Designer cannot reassign; a write as Sarah carries her name')
  const farah = q(`SELECT id FROM leads WHERE name = 'Farah Ahmad'`)
  await page.goto(`${BASE}/leads/${farah}`, { waitUntil: 'networkidle' })
  await page.getByRole('button', { name: 'Add' }).first().click()
  const pop = page.getByRole('dialog', { name: 'Assign Member' })
  await pop.waitFor()
  ok(await pop.getByText('Designers keep the leads assigned to them. Ask your manager to reassign.').isVisible(), 'Assign is read-only for a Designer')
  ok(await pop.getByText('Designer (you)').isVisible(), 'Sarah reads as "(you)" in the list')
  await page.screenshot({ path: `${OUT}/va-05-sarah-assign.png` })
  await pop.getByRole('button', { name: 'Close' }).last().click()
  const harpreet = q(`SELECT id FROM leads WHERE name = 'Harpreet Kaur'`)
  await page.goto(`${BASE}/leads/${harpreet}`, { waitUntil: 'networkidle' })
  await page.locator('[data-testid="next-follow-up"]').click()
  const dlg = page.getByRole('dialog', { name: 'Set a follow-up' })
  await dlg.waitFor()
  await dlg.getByRole('button', { name: /^When/ }).first().click().catch(async () => { await dlg.getByLabel(/When/).first().click() })
  await page.getByRole('button', { name: 'Today' }).click()
  await page.keyboard.press('Escape')
  await dlg.getByLabel(/^Task/).fill('UAT probe follow-up')
  await dlg.getByRole('button', { name: 'Save' }).click()
  await dlg.waitFor({ state: 'hidden', timeout: 10000 })
  ok(q(`SELECT creator_id FROM lead_tasks WHERE lead_id = '${harpreet}' AND title = 'UAT probe follow-up'`) === 'sarah', 'the follow-up task is created by Sarah')
  const acts = q(`SELECT group_concat(DISTINCT actor_id) FROM notifications WHERE lead_id = '${harpreet}' AND title LIKE '%UAT probe%'`)
  ok(acts === 'sarah', `its notifications name Sarah as the actor ("${acts}")`)
  await page.goto(`${BASE}/leads/${harpreet}/activity`, { waitUntil: 'networkidle' })
  await page.screenshot({ path: `${OUT}/va-06-sarah-activity.png` })

  console.log('Back to Dane')
  await page.getByRole('button', { name: /^Demo Studio/ }).click()
  await page.getByRole('menu', { name: 'View as' }).getByRole('menuitemradio').filter({ hasText: 'Dane' }).click()
  await page.getByText('Viewing as Dane · Owner').waitFor({ timeout: 10000 })
  ok(q(`SELECT id FROM members WHERE is_you = 1`) === 'dane', 'the flag is back on Dane')
  await page.goto(`${BASE}/leads`, { waitUntil: 'networkidle' })
  ok((await rows()) === daneRows, 'Dane sees every lead again')

  console.log('Phone 390')
  const phone = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  await phone.goto(`${BASE}/leads`, { waitUntil: 'networkidle' })
  await phone.getByRole('button', { name: 'More', exact: true }).click()
  const row = phone.getByRole('button', { name: /View as/ })
  ok(await row.isVisible(), 'More › View as row')
  ok((await row.innerText()).includes('Dane'), 'the row names Dane')
  await phone.screenshot({ path: `${OUT}/va-07-phone-more.png` })
  await row.click()
  await phone.getByRole('menuitemradio').first().waitFor()
  ok((await phone.getByRole('menuitemradio').count()) === 7, 'the sheet lists the 7 members')
  await phone.screenshot({ path: `${OUT}/va-08-phone-sheet.png` })

  console.log('Overflow at 320')
  const small = await browser.newPage({ viewport: { width: 320, height: 700 }, isMobile: true, hasTouch: true })
  await small.goto(`${BASE}/leads`, { waitUntil: 'networkidle' })
  await small.getByRole('button', { name: 'More', exact: true }).click()
  await small.getByRole('button', { name: /View as/ }).click()
  await small.getByRole('menuitemradio').first().waitFor()
  ok(await small.evaluate(() => document.documentElement.scrollWidth <= 320), 'no sideways scroll at 320')

  await browser.close()
  q(`DELETE FROM settings WHERE key = 'lead_visibility'`)
  console.log(`\n${pass} passed, ${fail} failed`)
  process.exit(fail ? 1 : 0)
})().catch((e) => { console.error(e); process.exit(2) })
