// UI sweep round S4 (REG-658) — Settings and the Company records: Members shows its own results and names what a deactivation lets go
// (Undo gives it back); the rows, the event table and the bank fit 768; the stacked Who and the message cards at 320–390; Insert a
// field at the caret; a taken name said on its field; the rounding and numbering words; a retired entity; the webhook's secrets never
// reach a member who may not manage them; the lead forms on the house switch table; the bell's due rows; the read-only lines; the
// Profile checks; the one-column ghosts.
const { chromium } = require('playwright')
const { execSync } = require('child_process')
const S = process.env.S, DB = process.env.TESTDB, BASE = 'http://localhost:3011'
const results = []
const ok = (name, pass, note = '') => { results.push({ name, pass, note }); console.log(`${pass ? 'PASS' : 'FAIL'}  ${name}${note ? ' — ' + note : ''}`) }
const sql = (q) => execSync(`sqlite3 "${DB}" "${q.replace(/"/g, '\\"')}"`).toString().trim()
const as = (id) => sql(`update members set is_you = case id when '${id}' then 1 else 0 end`)
async function step(name, fn) { try { await fn() } catch (e) { ok(name, false, e.message.split('\n').filter((l) => /waiting for|intercepts|Timeout|Error|expected/.test(l)).slice(0, 4).join(' | ')) } finally { as('dane') } }
async function ready(page) { await page.waitForLoadState('networkidle').catch(() => {}); await page.waitForTimeout(900) }
const snack = (page) => page.locator('[role="status"][aria-live="polite"]').innerText().catch(() => '')
const TOKEN = sql(`select json_extract(value,'$.webhooks[0].token') from settings where key='lead_capture'`)

;(async () => {
  const browser = await chromium.launch()
  const shot = (p, n) => p.screenshot({ path: `${S}/shots-sw4/${n}.png` })
  const desk = async () => { const ctx = await browser.newContext({ viewport: { width: 1440, height: 1024 } }); const page = await ctx.newPage(); page.setDefaultTimeout(12000); return { ctx, page } }

  await step('members', async () => {
    const { ctx, page } = await desk()
    sql(`insert or replace into settings (key, value, updated_at) values ('quote_rules', '{\"roundStep\":0,\"paymentLock\":false,\"backupApproverId\":\"james\",\"preparedBy\":\"member\"}', strftime('%s','now'))`)
    await page.goto(`${BASE}/company/members`); await ready(page)
    // #1 Add member shows at once
    await page.getByRole('button', { name: 'Add member' }).first().click()
    const dlg = page.getByRole('dialog', { name: 'Add member' }); await dlg.waitFor()
    await dlg.getByRole('button', { name: 'Add member' }).click(); await page.waitForTimeout(300)
    ok('an empty name says so on the field', await dlg.getByText('This field is required').isVisible())
    await dlg.getByRole('textbox').first().fill('Probe Person'); await dlg.getByRole('button', { name: 'Add member' }).click(); await page.waitForTimeout(1500)
    ok('a new member shows without a reload', await page.getByTestId('member-row').filter({ hasText: 'Probe Person' }).count() === 1)
    // #6 the confirm names the team and the backup seat; Undo gives them back
    const james = page.locator('[data-testid="member-row"][data-role="Manager"]')   // James is the one Manager; his Designers' rows name him too
    await james.getByRole('button', { name: 'Deactivate' }).click()
    const conf = page.getByRole('dialog', { name: 'Deactivate James?' }); await conf.waitFor()
    const msg = await conf.innerText()
    ok('the confirm names the team it lets go', /Michelle and Sarah will report to nobody/.test(msg), msg.replace(/\n/g, ' ').slice(0, 160))
    ok('and the backup approver seat', /backup approver/.test(msg))
    await shot(page, '01-deactivate-confirm')
    await conf.getByRole('button', { name: 'Deactivate' }).click(); await page.waitForTimeout(1500)
    ok('the deactivated member moves at once', await page.getByTestId('member-inactive').filter({ hasText: 'James' }).count() === 1)
    ok('the team and the seat were let go', sql(`select count(*) from members where manager_id='james'`) === '0' && !/james/.test(sql(`select value from settings where key='quote_rules'`)))
    await page.locator('[role="status"][aria-live="polite"]').getByRole('button', { name: 'Undo' }).click(); await page.waitForTimeout(1800)
    ok('Undo gives the team and the seat back', sql(`select count(*) from members where manager_id='james'`) === '2' && /"backupApproverId":"james"/.test(sql(`select value from settings where key='quote_rules'`)))
    ok('and the row is back in the list', await james.count() === 1 && await page.getByTestId('member-inactive').filter({ hasText: 'James' }).count() === 0)
    await ctx.close()
  })

  await step('members read-only + 768', async () => {
    as('sarah')
    const ctx = await browser.newContext({ viewport: { width: 768, height: 1024 }, isMobile: true, hasTouch: true }); const page = await ctx.newPage(); page.setDefaultTimeout(12000)
    await page.goto(`${BASE}/company/members`); await ready(page)
    ok('a Designer reads the read-only line', await page.getByTestId('read-only-line').isVisible())
    const spill = await page.getByTestId('member-row').evaluateAll((rows) => rows.filter((r) => { const c = r.closest('section')?.getBoundingClientRect(); return [...r.children].some((k) => k.getBoundingClientRect().right > (c?.right ?? 0) + 1) }).length)
    ok('768: every row stays inside its card', spill === 0, `${spill} rows spill`)
    await shot(page, '02-members-768')
    await page.goto(`${BASE}/company/questionnaire`); await ready(page)
    ok('the bank says it is read-only for a Designer', await page.getByTestId('read-only-line').isVisible())
    await page.goto(`${BASE}/company/integrations`); await ready(page)
    ok('Integrations: the read-only line', await page.getByTestId('read-only-line').isVisible())
    ok('a Designer is never sent the webhook token', !(await page.content()).includes(TOKEN) && await page.getByRole('button', { name: 'Copy URL' }).count() === 0)
    as('dane')
    await page.goto(`${BASE}/company/questionnaire`); await ready(page)
    const del = page.getByRole('button', { name: /^Delete “/ }).first()
    const out = await del.evaluate((b) => { const t = b.closest('[role="table"]').getBoundingClientRect(); const r = b.getBoundingClientRect(); return r.right - t.right }).catch(() => 99)
    ok('768: the bank’s Delete is fully in view', out <= 0, `${Math.round(out)}px`)
    await shot(page, '09-bank-768')
    await ctx.close()
  })

  await step('settings', async () => {
    const { ctx, page } = await desk()
    await page.goto(`${BASE}/settings?section=leads`); await ready(page)
    ok('Settings never ships the webhook token', !(await page.content()).includes(TOKEN))
    const add = page.getByTestId('lead-sources').getByRole('textbox', { name: /Add a source/ }).first()
    const existing = sql(`select source from leads where source is not null limit 1`)
    await add.fill(existing); await page.waitForTimeout(200)
    ok('a source already in the list says so as it is typed', await page.getByText(`${existing} is already in the list`).first().isVisible())
    ok('and Add waits', await page.getByTestId('lead-sources').getByRole('button', { name: 'Add', exact: true }).isDisabled())
    await add.fill('')
    await page.goto(`${BASE}/settings?section=quotes`); await ready(page)
    const trades = page.getByTestId('trade')
    const t0 = (await trades.nth(0).innerText()).trim().split('\n')[0], t1btn = trades.nth(1).getByRole('button').first()
    await t1btn.click(); const tdlg = page.getByTestId('trade-dialog'); await tdlg.waitFor()
    const nameBox = tdlg.getByRole('textbox').first(); await nameBox.fill(t0)
    await page.getByRole('dialog', { name: 'Trade' }).getByRole('button', { name: 'Save' }).click(); await page.waitForTimeout(400)
    ok('a taken trade name is said on the field, the dialog kept', await tdlg.getByText(`${t0} is already in the list`).isVisible())
    ok('the name box takes 40 characters, as the server', (await nameBox.getAttribute('maxlength')) === '40')
    await shot(page, '03-trade-taken')
    await page.getByRole('dialog', { name: 'Trade' }).getByRole('button', { name: 'Cancel' }).click(); await page.waitForTimeout(300)
    const round = page.getByTestId('rounding').getByRole('combobox').first()
    await round.click().catch(async () => page.getByLabel('Round selling prices to').click()); await page.waitForTimeout(250)
    await page.getByRole('option', { name: 'The nearest S$5' }).click(); await page.waitForTimeout(900)
    ok('the rounding line keeps S$', /round to the nearest S\$5/.test(await snack(page)), await snack(page))
    await page.goto(`${BASE}/settings?section=notifications`); await ready(page)
    await page.getByTestId('message-new_lead-whatsapp').getByRole('button', { name: 'Edit' }).click()
    const mdlg = page.getByRole('dialog').filter({ has: page.getByRole('textbox', { name: 'Message' }) }); await mdlg.waitFor()
    const ta = mdlg.getByRole('textbox', { name: 'Message' })
    await ta.evaluate((t) => { t.focus(); t.setSelectionRange(0, 0) }); await page.keyboard.press('Shift')
    await mdlg.getByRole('button', { name: 'Insert a field' }).click(); await page.waitForTimeout(250)
    await page.getByRole('menuitem', { name: 'The lead’s name' }).click(); await page.waitForTimeout(300)
    ok('Insert a field puts it at the caret', (await ta.inputValue()).startsWith('{lead_name} '), (await ta.inputValue()).slice(0, 40))
    await shot(page, '04-insert-field')
    await mdlg.getByRole('button', { name: 'Cancel' }).click()
    await ctx.close()
  })

  await step('studio + integrations', async () => {
    const { ctx, page } = await desk()
    sql(`update settings set value = json_insert(value, '$.details.entities[#]', json('{\"id\":\"old-co\",\"name\":\"Old Co Pte Ltd\",\"uen\":\"201900001A\",\"gstRegistered\":false,\"bankName\":\"\",\"accountName\":\"\",\"accountNo\":\"\",\"swift\":\"\",\"payNow\":\"\",\"retired\":true}')) where key='brand'`)
    await page.goto(`${BASE}/settings?section=studio`); await ready(page)
    ok('a retired entity says so in Settings › Studio', /Retired/i.test(await page.getByTestId('studio-entity').filter({ hasText: 'Old Co Pte Ltd' }).innerText()))
    sql(`update settings set value = json_set(value, '$.meta.connected', json('true'), '$.meta.page', 'Demo Studio · Facebook page') where key='lead_capture'`)
    await page.goto(`${BASE}/company/integrations`); await ready(page)
    ok('an Owner copies the webhook URL', await page.getByRole('button', { name: 'Copy URL' }).count() >= 1)
    ok('the lead forms are the house switch table', await page.getByRole('table', { name: 'Lead forms' }).getByRole('columnheader', { name: 'Sends leads' }).count() === 1)
    ok('no “dupes”', !/\bdupes\b/.test(await page.getByTestId('integrations').innerText()))
    await shot(page, '05-integrations')
    await ctx.close()
  })

  await step('bell', async () => {
    const { ctx, page } = await desk()
    await page.goto(`${BASE}/leads`); await ready(page)
    await page.getByRole('button', { name: /^Notifications/ }).first().click(); await page.waitForTimeout(1200)
    const due = await page.locator('[data-testid="notification-row"][data-derived]').count()
    ok('a due follow-up wears Due, never the unread dot', await page.locator('[data-testid="notification-row"][data-derived] [aria-label="Unread"]').count() === 0, `${due} due`)
    const mark = page.getByRole('button', { name: 'Mark all as read' })
    if (await mark.count()) {
      await mark.click(); await page.waitForTimeout(1200)
      const s = await snack(page)
      ok('Mark all as read says what stays', due ? /follow-ups? (is|are) due/.test(s) : /All caught up/.test(s), s)
    } else ok('Mark all as read says what stays', true, 'nothing unread to mark')
    await shot(page, '06-bell')
    await ctx.close()
  })

  await step('profile', async () => {
    const { ctx, page } = await desk()
    await page.goto(`${BASE}/company/profile`); await ready(page)
    const phone = page.locator('#details').getByLabel('Phone', { exact: true })
    await phone.fill('123'); await page.getByRole('button', { name: /^Save/ }).first().click(); await page.waitForTimeout(500)
    ok('a phone that is not a Singapore number says so', await page.getByText('Enter a valid 8-digit Singapore number').first().isVisible())
    await phone.fill('+65 6222 0188'); await page.waitForTimeout(200)
    ok('+65 and spaces are kept and pass', await page.getByText('Enter a valid 8-digit Singapore number').count() === 0)
    await ctx.close()
  })

  await step('phones and ghosts', async () => {
    sql(`insert into lead_custom_fields (id, label, field_type, options, is_required, order_index, is_active, created_at) values ('probe-cf', 'Probe field', 'text', null, 1, 0, 1, strftime('%s','now'))`)
    const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true }); const page = await ctx.newPage(); page.setDefaultTimeout(12000)
    await page.goto(`${BASE}/settings?section=notifications`); await ready(page)
    const who = await page.getByTestId('event-new_lead').locator('[data-label="Who"]').evaluate((e) => getComputedStyle(e, '::before').content)
    ok('390: the stacked Who is labelled', /Who/.test(who), who)
    await page.goto(`${BASE}/settings?section=leads`); await ready(page)
    const nameW = await page.getByTestId('add-reason-lost').getByRole('textbox').first().evaluate((e) => e.closest('[class*="field"]')?.getBoundingClientRect().width ?? e.getBoundingClientRect().width)
    ok('390: the Lost reason’s name box has room', nameW > 150, `${Math.round(nameW)}px`)
    const head = await page.getByRole('table', { name: 'Custom fields' }).locator('[role="row"]').first().evaluate((e) => getComputedStyle(e).display)
    ok('390: the custom fields keep their head', head !== 'none', head)
    await shot(page, '07-leads-390')
    await page.setViewportSize({ width: 320, height: 800 })
    await page.goto(`${BASE}/settings?section=notifications`); await ready(page)
    const over = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)
    ok('320: the message cards fit', over <= 0, `${over}px`)
    await page.goto(`${BASE}/company/integrations`, { waitUntil: 'commit' })
    const ghost = await page.locator('[aria-label="Loading company"] [class*="ghostForm"]').first().waitFor({ state: 'attached', timeout: 5000 }).then(() => true, () => false)
    ok('Integrations’ ghost is one column', ghost)
    await ctx.close()
  })

  await step('768 tables', async () => {
    const ctx = await browser.newContext({ viewport: { width: 768, height: 1024 }, isMobile: true, hasTouch: true }); const page = await ctx.newPage(); page.setDefaultTimeout(12000)
    await page.goto(`${BASE}/settings?section=notifications`); await ready(page)
    const wa = await page.getByRole('table', { name: 'Events and channels' }).evaluate((t) => { const h = [...t.querySelectorAll('[role="columnheader"]')].pop().getBoundingClientRect(); return h.right - t.getBoundingClientRect().right })
    ok('768: the WhatsApp column is in view', wa <= 0, `${Math.round(wa)}px`)
    await shot(page, '08-notifications-768')
    await ctx.close()
  })

  await browser.close()
  const passed = results.filter((r) => r.pass).length
  console.log(`${passed}/${results.length} passed`)
})()
