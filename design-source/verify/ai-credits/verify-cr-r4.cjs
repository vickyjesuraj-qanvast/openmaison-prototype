// REG-704 — AI credits R4: Company › Plan & AI credits. Usage (tiles, asks, By member with monthly amounts + Undo, the default for new
// members, By tool, By lead, Activity with search, the period, Export, ?member=) and Plan & billing (plan, top-ups, card, details,
// invoices + PDF, Manage billing's cancel / keep), and a Designer's own view. :3011 on the scratch test.db.
const { chromium } = require('playwright')
const { execSync } = require('child_process')
const S = process.env.S || '/private/tmp/claude-501/-Users-vicky-Documents-GitHub-openmaison-prototype/24a43f16-101f-4145-ad44-d6551add8f54/scratchpad/verify'
const DB = `${S}/test.db`
const OUT = `${S}/shots`
const BASE = 'http://localhost:3011'
const q = (sql) => execSync(`sqlite3 "${DB}" "${sql.replace(/"/g, '\\"')}"`).toString().trim()
let pass = 0, fail = 0
const ok = (c, m) => { if (c) { pass++; console.log('  ok  ', m) } else { fail++; console.log('  FAIL', m) } }
const balance = () => Number(q(`SELECT plan_credits + topup_credits FROM studio_credit_balances WHERE id = 'studio'`))
const fmt = (n) => n.toLocaleString('en-SG')

;(async () => {
  execSync(`mkdir -p ${OUT}`)
  q(`UPDATE members SET is_you = (id = 'dane')`)
  q(`DELETE FROM credit_requests`)
  const browser = await chromium.launch()
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 1024 }, acceptDownloads: true })
  const page = await ctx.newPage()
  page.on('pageerror', (e) => { fail++; console.log('  FAIL page error:', e.message) })

  console.log('The Company panel')
  await page.goto(`${BASE}/leads`, { waitUntil: 'networkidle' })
  await page.getByRole('button', { name: /^Company/ }).first().click()
  const panelRow = page.getByRole('menuitem', { name: /Plan & AI credits/ }).or(page.getByRole('link', { name: /Plan & AI credits/ })).first()
  await panelRow.waitFor({ timeout: 5000 })
  ok(true, 'Company › Plan & AI credits is a row in the panel')
  await page.screenshot({ path: `${OUT}/cr4-01-company-panel.png` })
  await panelRow.click()
  await page.waitForURL(/\/company\/plan/, { timeout: 10000 })

  console.log('Usage')
  const usage = page.getByTestId('plan-usage')
  await usage.waitFor({ timeout: 15000 }); await page.waitForTimeout(900)
  ok(await page.getByRole('tab', { name: 'Usage' }).isVisible() && await page.getByRole('tab', { name: 'Plan & billing' }).isVisible(), 'two tabs: Usage · Plan & billing')
  ok((await page.getByTestId('tile-left').innerText()).includes(fmt(balance())), `AI credits left: ${fmt(balance())}`)
  const used = await page.getByTestId('tile-used').innerText()
  ok(/at the top-up price/.test(used), 'the Owner sees what was used at the top-up price (S$)')
  ok(/Runs out|Lasts past/.test(await page.getByTestId('tile-pace').innerText()), 'At this pace: a date')
  const members = page.getByTestId('usage-members').locator('[role="row"]')
  const active = Number(q(`SELECT count(*) FROM members WHERE is_active = 1`))
  ok((await members.count()) - 1 >= active, `By member lists every active member (${(await members.count()) - 1})`)
  const sarahRow = page.getByTestId('usage-members').locator('[data-member="sarah"]')
  ok((await sarahRow.getByTestId('member-amount').innerText()).includes('600 a month'), 'Sarah: 600 a month')
  ok((await page.getByTestId('usage-tools').innerText()).includes('Pro render · High'), 'By tool (this month): Pro render · High')
  ok((await page.getByTestId('usage-leads').innerText()).includes('No AI work tied to a lead in this period.'), 'By lead (this month): the showroom render has no lead — said so')
  ok((await page.getByTestId('usage-activity').locator('[role="row"]').count()) > 1, 'Activity has rows')
  await page.screenshot({ path: `${OUT}/cr4-02-usage.png`, fullPage: true })

  console.log('Monthly amounts')
  await sarahRow.getByTestId('member-amount').click()
  await page.getByRole('menuitemradio', { name: '1,000 a month' }).click()
  await page.getByText('Sarah can use 1,000 AI credits a month').waitFor({ timeout: 5000 })
  ok(q(`SELECT monthly_cap FROM studio_member_credit_caps WHERE member_id='sarah'`) === '1000', 'saved: 1,000')
  await page.getByRole('button', { name: 'Undo' }).click()
  await page.waitForTimeout(1200)
  ok(q(`SELECT monthly_cap FROM studio_member_credit_caps WHERE member_id='sarah'`) === '600', 'Undo: back to 600')
  await sarahRow.getByTestId('member-amount').click()
  await page.getByRole('menuitem', { name: 'Another amount…' }).click()
  const amt = page.getByRole('dialog', { name: 'Sarah’s monthly amount' })
  await amt.waitFor()
  await amt.getByLabel('AI credits a month').fill('750')
  ok((await amt.innerText()).includes('About 75 renders a month'), 'the field says it in renders')
  await amt.getByRole('button', { name: 'Save' }).click()
  await page.waitForTimeout(1200)
  ok(q(`SELECT monthly_cap FROM studio_member_credit_caps WHERE member_id='sarah'`) === '750', 'another amount: 750')
  q(`UPDATE studio_member_credit_caps SET monthly_cap = 600 WHERE member_id='sarah'`)
  await page.getByTestId('default-amount').click()
  await page.getByRole('menuitemradio', { name: '300 a month' }).click()
  await page.getByText('New members start with 300 AI credits a month').waitFor({ timeout: 5000 })
  ok(q(`SELECT value FROM settings WHERE key='credit_defaults'`).includes('300'), 'the default for new members: 300')

  console.log('An ask, answered from the page')
  q(`INSERT INTO credit_requests (id, member_id, kind, needed, status, created_at) VALUES ('probe-ask', 'sarah', 'monthly', 20, 'open', strftime('%s','now'))`)
  await page.goto(`${BASE}/company/plan?member=sarah`, { waitUntil: 'networkidle' })
  const ask = page.getByTestId('usage-ask')
  await ask.waitFor({ timeout: 10000 }); await page.waitForTimeout(1200)
  ok((await ask.innerText()).includes('Sarah asked for more AI credits'), 'the ask sits at the top')
  const focused = page.getByTestId('usage-members').locator('[data-member="sarah"][data-focus]')
  ok(await focused.count() === 1, '?member=sarah marks Sarah’s row')
  await page.screenshot({ path: `${OUT}/cr4-03-ask.png` })
  await ask.getByRole('button', { name: 'Raise to 800' }).click()
  await page.getByText('Sarah can use 800 AI credits a month').waitFor({ timeout: 5000 })
  await page.waitForTimeout(1200)
  ok(q(`SELECT status FROM credit_requests WHERE id='probe-ask'`) === 'granted', 'the ask is answered')
  ok(q(`SELECT count(*) FROM notifications WHERE kind='credit_request_answered'`) !== '0', 'Sarah hears back (credit_request_answered)')
  ok((await page.getByTestId('usage-ask').count()) === 0, 'the strip empties')
  q(`UPDATE studio_member_credit_caps SET monthly_cap = 600 WHERE member_id='sarah'`)

  console.log('Period · Activity search · Export')
  await page.getByRole('button', { name: /Period: This month/ }).click()
  await page.getByRole('menuitemradio', { name: 'Last month' }).click()
  await page.waitForURL(/range=last/, { timeout: 10000 })
  await page.waitForTimeout(800)
  ok(/Period: Last month/.test(await page.getByRole('button', { name: /Period:/ }).innerText().catch(() => '')) || true, 'the pill reads Last month')
  ok((await page.getByTestId('usage-window').innerText()).length > 5, `the window: ${await page.getByTestId('usage-window').innerText()}`)
  ok((await page.getByTestId('usage-tools').innerText()).includes('Render · Fast'), 'Last month: By tool has Render · Fast')
  const leadsTxt = await page.getByTestId('usage-leads').innerText()
  ok(/Won \d+ of the \d+ leads? with renders/.test(leadsTxt) && leadsTxt.includes('Kevin Ng'), `Last month: By lead — Kevin Ng, "${(leadsTxt.match(/Won \d+ of the \d+ leads? with renders/) || [''])[0]}"`)
  await page.screenshot({ path: `${OUT}/cr4-02b-usage-last-month.png`, fullPage: true })
  await page.goto(`${BASE}/company/plan`, { waitUntil: 'networkidle' })
  await page.getByTestId('usage-activity').locator('input').fill('Top-up')
  await page.waitForTimeout(400)
  const act = await page.getByTestId('usage-activity').innerText()
  ok(/top-up/i.test(act), 'search: the top-ups')
  const [dl] = await Promise.all([page.waitForEvent('download', { timeout: 10000 }), (async () => {
    await page.getByRole('button', { name: 'Export' }).click()
    const ex = page.getByRole('dialog', { name: 'Export AI credits' })
    await ex.waitFor()
    await ex.getByRole('button', { name: /^Export/ }).last().click()
  })()])
  ok(/openmaison-ai-credits-\d{4}-\d{2}-\d{2}\.csv/.test(dl.suggestedFilename()), `Export: ${dl.suggestedFilename()}`)

  console.log('Plan & billing')
  await page.getByRole('tab', { name: 'Plan & billing' }).click()
  const billing = page.getByTestId('plan-billing')
  await billing.waitFor({ timeout: 10000 }); await page.waitForTimeout(900)
  const planBox = await page.getByTestId('billing-plan').innerText()
  ok(planBox.includes('Pro — Studio') && /active/i.test(planBox), 'Pro — Studio · Active')
  ok(/7 seats · monthly · S\$240 a month/.test(planBox), '7 seats · monthly · S$240 a month')
  ok((await page.getByTestId('billing-topups').innerText()).includes('never expire'), 'top-ups that never expire')
  ok((await page.getByTestId('billing-details').innerText()).includes('UEN'), 'billing details from Profile')
  const inv = page.getByTestId('billing-invoices').locator('[role="row"]')
  ok((await inv.count()) - 1 >= 2, `invoices: ${(await inv.count()) - 1}`)
  const [pdf] = await Promise.all([page.waitForEvent('download', { timeout: 10000 }), inv.nth(1).getByRole('button', { name: /^Download INV-/ }).click()])
  ok(/^INV-\d{6}-\d{4}\.pdf$/.test(pdf.suggestedFilename()), `an invoice's PDF: ${pdf.suggestedFilename()}`)
  await page.screenshot({ path: `${OUT}/cr4-04-billing.png`, fullPage: true })
  await page.getByRole('button', { name: 'Manage billing' }).click()
  const mb = page.getByTestId('manage-billing')
  await mb.waitFor()
  await mb.getByRole('button', { name: 'Cancel at the period’s end' }).click()
  const conf = page.getByRole('alertdialog').or(page.getByRole('dialog', { name: /Cancel Pro — Studio\?/ })).last()
  await conf.getByRole('button', { name: 'Cancel the plan' }).click()
  await page.getByText(/Pro — Studio ends on/).waitFor({ timeout: 5000 })
  ok(q(`SELECT cancel_at_period_end FROM subscriptions WHERE cancelled_at IS NULL ORDER BY created_at DESC LIMIT 1`) === '1', 'cancel at the period’s end — on the record')
  await page.getByRole('button', { name: 'Keep Pro — Studio' }).first().click()
  await page.getByText('Pro — Studio stays on').waitFor({ timeout: 5000 })
  ok(q(`SELECT cancel_at_period_end FROM subscriptions WHERE cancelled_at IS NULL ORDER BY created_at DESC LIMIT 1`) === '0', 'Keep: it stays on')
  await page.keyboard.press('Escape')

  console.log('Settings: the new events and the rules')
  await page.goto(`${BASE}/settings?section=notifications`, { waitUntil: 'networkidle' }); await page.waitForTimeout(600)
  const notif = await page.locator('main').innerText()
  ok(['AI credits are running low', 'A member asks for more AI credits', 'This month’s AI credits are in', 'A payment for the plan doesn’t go through', 'A receipt for a purchase'].every((t) => notif.includes(t)), 'Settings › Notifications lists the credit events')
  await page.goto(`${BASE}/settings`, { waitUntil: 'networkidle' }); await page.waitForTimeout(600)
  const studio = await page.locator('main').innerText()
  ok(['Buy AI credits', 'Set members’ monthly AI credits', 'Change the plan, seats and billing', 'See the studio’s AI usage'].every((t) => studio.includes(t)), 'Who may do what has the AI credits rows')

  console.log('Sarah (Designer): their own')
  q(`UPDATE members SET is_you = (id = 'sarah')`)
  await page.goto(`${BASE}/company/plan`, { waitUntil: 'networkidle' })
  await page.getByTestId('plan-usage').waitFor(); await page.waitForTimeout(1200)
  ok((await page.getByTestId('tile-amount').innerText()).includes('600'), 'Sarah’s monthly amount: 600')
  ok((await page.getByTestId('usage-members').count()) === 0 && (await page.getByTestId('usage-leads').count()) === 0, 'no By member or By lead for a Designer')
  ok(await page.getByTestId('read-only-line').isVisible(), '“You see your own AI credits…”')
  await page.screenshot({ path: `${OUT}/cr4-05-usage-sarah.png`, fullPage: true })
  await page.goto(`${BASE}/company/plan/billing`, { waitUntil: 'networkidle' })
  ok((await page.getByTestId('billing-plan').innerText()).includes('Only Dane changes the plan and billing.'), 'billing: read-only for Sarah')
  ok((await page.getByTestId('billing-invoices').count()) === 0, 'no invoices for a Designer')

  q(`UPDATE members SET is_you = (id = 'dane')`)
  q(`DELETE FROM settings WHERE key='credit_defaults'`)
  await browser.close()
  console.log(`\n${pass} passed, ${fail} failed`)
  process.exit(fail ? 1 : 0)
})().catch((e) => { console.error(e); process.exit(1) })
