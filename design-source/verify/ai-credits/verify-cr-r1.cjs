// REG-701 · 702 · 705 — AI credits R1–R2: the rail slot (both states), the credits card, View as › Studio plan, Plans end to end.
// Against :3011 on the scratch test.db (never local.db).
const { chromium } = require('playwright')
const { execSync } = require('child_process')
const S = process.env.S || '/private/tmp/claude-501/-Users-vicky-Documents-GitHub-openmaison-prototype/24a43f16-101f-4145-ad44-d6551add8f54/scratchpad/verify'
const DB = `${S}/test.db`
const OUT = `${S}/shots`
const BASE = 'http://localhost:3011'
const q = (sql) => execSync(`sqlite3 "${DB}" "${sql.replace(/"/g, '\\"')}"`).toString().trim()
let pass = 0, fail = 0
const ok = (c, m) => { if (c) { pass++; console.log('  ok  ', m) } else { fail++; console.log('  FAIL', m) } }
const ledgerSum = () => Number(q(`SELECT coalesce(sum(credits),0) FROM credit_ledger WHERE reason != 'shadow_spend'`))
const balance = () => Number(q(`SELECT plan_credits + topup_credits FROM studio_credit_balances WHERE id = 'studio'`))

;(async () => {
  execSync(`mkdir -p ${OUT}`)
  q(`UPDATE members SET is_you = (id = 'dane')`)
  const browser = await chromium.launch()
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 1024 } })
  const page = await ctx.newPage()
  page.on('pageerror', (e) => { fail++; console.log('  FAIL page error:', e.message) })

  console.log('Dane (Owner) · Pro — Studio')
  await page.goto(`${BASE}/leads`, { waitUntil: 'networkidle' })
  const row = page.getByTestId('rail-credits')
  await row.waitFor({ timeout: 15000 })
  const bal = balance()
  ok((await row.innerText()).replace(/\s+/g, ' ').includes(bal.toLocaleString('en-SG')), `the rail row reads the balance (${bal.toLocaleString('en-SG')})`)
  ok(bal === ledgerSum(), `balance ${bal} = the ledger's sum ${ledgerSum()}`)
  ok((await page.getByTestId('rail-upgrade').count()) === 0, 'no Upgrade row on a paid plan')
  const rb = await row.boundingBox()
  ok(rb && Math.round(rb.height) === 36, `the row keeps the rail item's 36px (${rb && rb.height})`)
  await page.screenshot({ path: `${OUT}/cr1-01-rail-collapsed.png`, clip: { x: 0, y: 700, width: 420, height: 324 } })
  await row.hover(); await page.waitForTimeout(600)
  ok(await page.getByRole('tooltip').filter({ hasText: 'AI credits' }).first().isVisible().catch(() => false), 'collapsed: the tooltip says the balance')
  await row.click()
  const card = page.getByTestId('credits-card')
  await card.waitFor(); await page.waitForTimeout(400)
  ok(await card.getByTestId('credits-card-balance').innerText() === bal.toLocaleString('en-SG'), 'the card leads with the balance')
  ok(/Refreshes \d{1,2} \w{3} · in \d+ days/.test(await card.innerText()), 'the card says when it refreshes ("10 Oct · in N days")')
  ok(/about [\d,]+ renders/.test(await card.innerText()), 'and what it comes to in renders')
  ok(await card.getByRole('button', { name: /Buy 1,000/ }).isVisible(), 'the Owner can buy 1,000 · S$20')
  ok(await card.getByRole('button', { name: 'See usage' }).isVisible() && await card.getByRole('button', { name: 'Change plan' }).isVisible(), 'See usage · Change plan')
  await page.screenshot({ path: `${OUT}/cr1-02-card-owner.png` })
  await page.keyboard.press('Escape'); await card.waitFor({ state: 'hidden' })
  ok(true, 'Esc closes the card')

  console.log('Expanded rail')
  await page.evaluate(() => localStorage.setItem('om.rail.expanded', '1'))
  await page.reload({ waitUntil: 'networkidle' })
  await row.waitFor(); await page.waitForTimeout(900)
  const eb = await row.boundingBox()
  ok(eb && Math.round(eb.width) === 200, `expanded: the row is the rail's 200 (${eb && eb.width})`)
  ok((await row.innerText()).replace(/\s+/g, ' ').includes(`${bal.toLocaleString('en-SG')} AI credits`), 'expanded: "11,610 AI credits"')
  await page.screenshot({ path: `${OUT}/cr1-03-rail-expanded.png`, clip: { x: 0, y: 700, width: 420, height: 324 } })

  console.log('View as › Studio plan · Free')
  const block = page.getByRole('button', { name: /^Demo Studio/ })
  await block.click()
  const menu = page.getByRole('menu', { name: 'View as' })
  await menu.waitFor()
  const plans = menu.getByTestId('demo-plan')
  ok(await plans.isVisible(), 'View as has the Studio plan group')
  ok((await plans.getByRole('menuitemradio', { name: /^Pro — Studio The base plan/ }).getAttribute('aria-checked')) === 'true', 'Pro — Studio is ticked')
  await page.screenshot({ path: `${OUT}/cr1-04-view-as-plans.png` })
  await plans.getByRole('menuitemradio', { name: /^Free/ }).click()
  await page.getByText('Studio plan: Free (demo)').waitFor({ timeout: 10000 })
  ok(true, 'snackbar: Studio plan: Free (demo)')
  const up = page.getByTestId('rail-upgrade')
  await up.waitFor({ timeout: 10000 })
  ok(q(`SELECT plan_id FROM subscriptions WHERE cancelled_at IS NULL ORDER BY created_at DESC LIMIT 1`) === 'free', 'the studio is on Free')
  ok(balance() === ledgerSum(), 'Free: balance still = the ledger')
  const freeBal = balance()
  ok((await up.innerText()).includes('Upgrade') && (await up.innerText()).includes(freeBal.toLocaleString('en-SG')), `Upgrade with the balance quiet at its end (${freeBal})`)
  await page.screenshot({ path: `${OUT}/cr1-05-rail-free.png`, clip: { x: 0, y: 700, width: 420, height: 324 } })

  console.log('Plans · Choose')
  await up.click()
  const dlg = page.getByRole('dialog', { name: 'Plans' })
  await dlg.waitFor()
  await page.waitForTimeout(400)
  const choose = dlg.getByTestId('plans-choose')
  ok(await choose.isVisible(), 'Plans opens on Choose, over the page (no navigation)')
  ok(page.url().endsWith('/leads'), 'still on /leads')
  const pro = dlg.getByTestId('plan-pro')
  ok((await pro.innerText()).includes('Fits your team of 7'), 'Pro: Fits your team of 7')
  ok((await dlg.getByTestId('plan-free').innerText()).includes('Your plan'), 'Free: Your plan')
  ok((await dlg.getByTestId('plan-price').innerText()) === 'S$240', 'Studio for 7 seats: S$240 a month')
  const box = await dlg.boundingBox()
  ok(box && Math.round(box.x) === 48 && Math.round(box.y) === 48, `the xxl modal sits 48px from the edges (${box && [box.x, box.y]})`)
  await page.screenshot({ path: `${OUT}/cr1-06-plans-choose.png` })
  await dlg.getByRole('radio', { name: 'Annual · 1 month free' }).click()
  ok((await dlg.getByTestId('plan-price').innerText()) === 'S$2,640', 'annual: S$2,640 a year (11 × 240)')
  ok((await pro.innerText()).includes('S$220 a month, saves S$240'), 'annual: the per-month figure and the S$ saved')
  await dlg.getByRole('radio', { name: 'Freelance' }).click()
  ok(await dlg.getByTestId('plan-why').isVisible(), 'Freelance says why it won’t fit (7 members)')
  ok(await dlg.getByTestId('plans-continue').isDisabled(), 'Continue waits')
  await page.screenshot({ path: `${OUT}/cr1-07-plans-freelance.png` })
  await dlg.getByRole('radio', { name: 'Studio' }).click()
  await dlg.getByRole('radio', { name: 'Monthly' }).click()
  await dlg.getByRole('button', { name: 'Compare everything' }).click()
  ok(await dlg.getByText('Quote X-Ray').first().isVisible(), 'Compare everything opens the website’s table')
  await dlg.getByTestId('plans-continue').click()

  console.log('Plans · Review')
  const review = dlg.getByTestId('plans-review')
  await review.waitFor()
  ok((await dlg.getByTestId('plans-seats').innerText()).includes('7'), 'seats default to the 7 active members')
  await dlg.getByRole('button', { name: 'More seats' }).click()
  ok((await dlg.getByTestId('plans-seats').innerText()).includes('8'), 'a seat more: 8')
  ok((await dlg.getByTestId('plans-today').innerText()) === 'S$275.00', 'today: S$275.00 for 8 seats')
  await dlg.getByRole('button', { name: 'Fewer seats' }).click()
  await dlg.locator('label[data-size="sm"]').filter({ has: page.getByRole('switch', { name: 'Start with 14 days free' }) }).click()
  ok((await dlg.getByTestId('plans-today').innerText()) === 'S$0.00', 'the 14-day trial: S$0.00 today')
  ok((await dlg.getByTestId('plans-pay').innerText()).includes('Start the free trial'), 'the press says Start the free trial')
  await page.screenshot({ path: `${OUT}/cr1-08-plans-review.png` })
  await dlg.locator('label[data-size="sm"]').filter({ has: page.getByRole('switch', { name: 'Start with 14 days free' }) }).click()
  ok((await dlg.getByTestId('plans-pay').innerText()).includes('Pay S$240'), 'without the trial: Pay S$240')

  console.log('Plans · Pay → Done')
  await dlg.getByTestId('plans-pay').click()
  const co = dlg.getByTestId('demo-checkout')
  await co.waitFor()
  ok((await co.innerText()).includes('S$240.00'), 'the demo checkout shows the amount')
  ok((await co.innerText()).includes('UEN'), 'billed to the studio, UEN filled in')
  ok(!(await co.locator('input').count()), 'no card fields in the demo checkout')
  await page.screenshot({ path: `${OUT}/cr1-09-plans-pay.png` })
  const before = ledgerSum()
  await co.getByRole('button', { name: 'Complete demo payment' }).click()
  await dlg.getByTestId('plans-done').waitFor({ timeout: 15000 })
  await page.waitForTimeout(1400)
  const count = await dlg.getByTestId('plans-count').innerText()
  const after = balance()
  ok(count === after.toLocaleString('en-SG'), `Done counts the credits in (${count})`)
  ok(ledgerSum() === after, `balance ${after} = ledger after the upgrade`)
  ok(q(`SELECT count(*) FROM credit_ledger WHERE credits = 10500`) !== '0', `the month's 10,500 arrived as its own row (Free's unused plan credits ended: net +${after - before})`)
  ok(q(`SELECT plan_id || '/' || status || '/' || seats FROM subscriptions WHERE cancelled_at IS NULL ORDER BY created_at DESC LIMIT 1`) === 'pro_studio/active/7', 'Pro — Studio · active · 7 seats')
  ok(Number(q(`SELECT count(*) FROM invoices WHERE plan_name LIKE 'Pro — Studio%'`)) >= 2, 'a tax invoice for the plan')
  ok(await page.getByTestId('rail-upgrade').isVisible(), 'the rail still reads Upgrade while Plans is open (the moment waits)')
  await page.screenshot({ path: `${OUT}/cr1-10-plans-done.png` })
  await dlg.getByTestId('plans-back-to-work').click()
  await page.getByTestId('rail-credits').waitFor({ timeout: 5000 })
  ok(true, 'closing Plans: the gem turns and the slot becomes the credits row')
  await page.waitForTimeout(1200)
  ok((await page.getByTestId('rail-credits').innerText()).replace(/\s+/g, ' ').includes(after.toLocaleString('en-SG')), 'the row counted up to the new balance')
  await page.screenshot({ path: `${OUT}/cr1-11-rail-after.png`, clip: { x: 0, y: 700, width: 420, height: 324 } })

  console.log('View as › Almost out, then back to the base')
  await page.getByRole('button', { name: /^Demo Studio/ }).click()
  await page.getByRole('menu', { name: 'View as' }).getByTestId('demo-plan').getByRole('menuitemradio', { name: /^Almost out/ }).click()
  await page.getByText('Studio plan: Pro — Studio · almost out (demo)').waitFor({ timeout: 10000 })
  await page.waitForTimeout(800)
  ok(balance() === 15 && balance() === ledgerSum(), 'Almost out: 15 AI credits, still = the ledger')
  ok(['low', 'empty'].includes(await page.getByTestId('rail-credits').getAttribute('data-tone')), `the rail row takes the low tone (${await page.getByTestId('rail-credits').getAttribute('data-tone')})`)
  await page.getByRole('button', { name: /^Demo Studio/ }).click()
  await page.getByRole('menu', { name: 'View as' }).getByTestId('demo-plan').getByRole('menuitemradio', { name: /^Pro — Studio The base plan/ }).click()
  await page.getByText('Studio plan: Pro — Studio (demo)').waitFor({ timeout: 10000 })
  await page.waitForTimeout(800)
  ok(balance() >= 10500 && balance() === ledgerSum(), `the base plan brings a healthy month back (${balance()})`)

  console.log('One trial per studio')
  const pickPlan = async (name) => {
    await page.getByRole('button', { name: /^Demo Studio/ }).click()
    await page.getByRole('menu', { name: 'View as' }).getByTestId('demo-plan').getByRole('menuitemradio', { name }).click()
    await page.waitForTimeout(1500)
  }
  await pickPlan(/^Pro — Studio · trial/)
  ok(q(`SELECT count(*) FROM subscriptions WHERE trial_ends_at IS NOT NULL`) !== '0', 'the demo trial is on the record')
  await pickPlan(/^Free/)
  await page.getByTestId('rail-upgrade').waitFor({ timeout: 10000 })
  await page.getByTestId('rail-upgrade').click()
  const d2 = page.getByRole('dialog', { name: 'Plans' })
  await d2.waitFor(); await page.waitForTimeout(400)
  ok(!(await d2.getByTestId('plan-pro').innerText()).includes('14-day free trial'), 'Choose no longer offers the trial')
  await d2.getByTestId('plans-continue').click()
  await d2.getByTestId('plans-review').waitFor()
  ok((await d2.getByTestId('plans-review').innerText()).includes('The studio has had its free trial'), 'Review: “The studio has had its free trial”')
  ok(await d2.getByRole('switch', { name: 'Start with 14 days free' }).isDisabled(), 'the trial switch is off and disabled')
  ok((await d2.getByTestId('plans-pay').innerText()).includes('Pay S$240'), 'the press says Pay S$240')
  await page.keyboard.press('Escape')
  await pickPlan(/^Pro — Studio The base plan/)

  console.log('Sarah (Designer, 600 a month)')
  q(`UPDATE members SET is_you = (id = 'sarah')`)
  await page.goto(`${BASE}/leads`, { waitUntil: 'networkidle' }); await page.waitForTimeout(900)
  const srow = page.getByTestId('rail-credits')
  await srow.waitFor()
  const t = (await srow.innerText()).replace(/\s+/g, ' ')
  ok(/of your 600/.test(t), `Sarah's row: the amount left ("${t}")`)
  await srow.click()
  const scard = page.getByTestId('credits-card')
  await scard.waitFor(); await page.waitForTimeout(400)
  ok(!(await scard.getByRole('button', { name: /Buy 1,000/ }).count()), 'Sarah cannot buy')
  ok(!(await scard.innerText()).includes(after.toLocaleString('en-SG')), 'the studio’s balance is not shown to a Designer')
  await page.screenshot({ path: `${OUT}/cr1-12-card-sarah.png` })
  await page.keyboard.press('Escape')
  await page.getByTestId('rail-credits').click()
  await page.getByTestId('credits-card').getByRole('button', { name: 'Change plan' }).or(page.getByTestId('credits-card').getByRole('button', { name: 'See plans' })).first().click()
  const sdlg = page.getByRole('dialog', { name: 'Plans' })
  await sdlg.waitFor()
  await sdlg.getByTestId('plans-continue').isDisabled()
  ok((await sdlg.getByTestId('plan-pro').innerText()).includes('Your plan'), 'Sarah sees Pro as Your plan')
  await page.keyboard.press('Escape')

  q(`UPDATE members SET is_you = (id = 'dane')`)
  await browser.close()
  console.log(`\n${pass} passed, ${fail} failed`)
  process.exit(fail ? 1 : 0)
})().catch((e) => { console.error(e); process.exit(1) })
