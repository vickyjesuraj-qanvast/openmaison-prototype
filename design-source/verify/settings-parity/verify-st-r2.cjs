// Settings parity round 2 (REG-646) — who may change the studio: Company › Members adds, deactivates (with Undo) and reactivates members
// under the Owner rules; a deactivated member leaves the pickers and the notices but keeps their records; Owners and Admins alone change
// Notifications, Integrations, Profile, the brand kit and a template's default / rename / delete (the menus say why); More › Company on a phone.
const { chromium } = require('playwright')
const { execSync } = require('child_process')
const S = process.env.S, DB = process.env.TESTDB, BASE = 'http://localhost:3011'
const results = []
const ok = (name, pass, note = '') => { results.push({ name, pass, note }); console.log(`${pass ? 'PASS' : 'FAIL'}  ${name}${note ? ' — ' + note : ''}`) }
const sql = (q) => execSync(`sqlite3 "${DB}" "${q.replace(/"/g, '\\"')}"`).toString().trim()
async function step(name, fn) { try { await fn() } catch (e) { ok(name, false, e.message.split('\n').filter((l) => /waiting for|intercepts|Timeout|Error|expected/.test(l)).slice(0, 4).join(' | ')) } finally { sql(`update members set is_you = case id when 'dane' then 1 else 0 end`) } }
async function ready(page) { await page.waitForLoadState('networkidle').catch(() => {}); await page.waitForTimeout(900) }
async function snack(page, text) { await page.getByText(text, { exact: false }).first().waitFor({ timeout: 6000 }) }
const as = (id) => sql(`update members set is_you = case id when '${id}' then 1 else 0 end`)
const MICHELLE0 = sql(`select coalesce(manager_id, 'none') || '|' || accepting_leads from members where id='michelle'`)
const row = (page, name) => page.getByTestId('member-row').filter({ has: page.locator('span[class*="__name"]').filter({ hasText: new RegExp(`^${name}`) }) })

;(async () => {
  const browser = await chromium.launch()
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 1024 } })
  const page = await ctx.newPage()
  page.setDefaultTimeout(12000)
  const shot = (n, p = page) => p.screenshot({ path: `${S}/shots-st2/${n}.png` })

  await step('an Owner adds a member', async () => {
    await page.goto(`${BASE}/company/members`); await page.getByTestId('members').waitFor(); await ready(page)
    await page.getByRole('button', { name: 'Add member' }).click()
    const dlg = page.getByRole('dialog', { name: 'Add member' })
    await dlg.getByRole('button', { name: 'Add member' }).click()
    ok('a name is asked for', /This field is required/.test(await dlg.innerText()))   // (sweep S4 #23) the house message
    await dlg.getByLabel('Name').fill('Priya'); await dlg.getByLabel('Phone').fill('1234')
    await dlg.getByRole('button', { name: 'Add member' }).click()
    ok('a wrong phone is refused as typed', /Enter a valid 8-digit Singapore number/.test(await dlg.innerText()))
    await dlg.getByLabel('Phone').fill('91234567'); await dlg.getByLabel('Email').fill('priya@demostudio.sg')
    await shot('01-add-member')
    await dlg.getByRole('button', { name: 'Add member' }).click(); await snack(page, 'Priya added as a Designer')
    ok('the member is on the record, active, with the phone', sql(`select role || '|' || is_active || '|' || phone from members where name='Priya'`) === 'Designer|1|91234567')
    await page.getByRole('button', { name: 'Add member' }).click()
    await page.getByRole('dialog', { name: 'Add member' }).getByLabel('Name').fill('Sarah')
    await page.getByRole('dialog', { name: 'Add member' }).getByRole('button', { name: 'Add member' }).click(); await snack(page, 'Sarah is already a member')
    ok('a second Sarah is refused', sql(`select count(*) from members where name='Sarah'`) === '1')
    await page.keyboard.press('Escape')
  })

  await step('deactivate names the open work, and Undo brings the member back', async () => {
    await page.goto(`${BASE}/company/members`); await ready(page)
    await row(page, 'Michelle').getByRole('button', { name: 'Deactivate' }).click()
    const dlg = page.getByRole('dialog', { name: 'Deactivate Michelle?' })
    ok('the confirm names her open leads', /open lead/.test(await dlg.innerText()), (await dlg.innerText()).slice(0, 160))
    await shot('02-deactivate-confirm')
    await dlg.getByRole('button', { name: 'Deactivate' }).click(); await snack(page, 'Michelle deactivated')
    ok('deactivated on the record', sql(`select is_active from members where id='michelle'`) === '0')
    await page.getByRole('button', { name: 'Undo' }).click(); await snack(page, 'Michelle is back')
    ok('Undo brings her back exactly — her manager, open to leads as before', sql(`select is_active || '|' || coalesce(manager_id, 'none') || '|' || accepting_leads from members where id='michelle'`) === `1|${MICHELLE0}`)
  })

  await step('a deactivated member keeps her records and leaves the pickers', async () => {
    const lead = sql(`select l.id from leads l where l.deleted_at is null and l.stage not in ('Won','Lost') and exists (select 1 from lead_assignees a where a.lead_id=l.id and a.member_id='sarah') limit 1`)
    const other = sql(`select l.id from leads l where l.deleted_at is null and not exists (select 1 from lead_assignees a where a.lead_id=l.id) limit 1`)
    await page.goto(`${BASE}/company/members`); await ready(page)
    await row(page, 'Sarah').getByRole('button', { name: 'Deactivate' }).click()
    await page.getByRole('dialog', { name: 'Deactivate Sarah?' }).getByRole('button', { name: 'Deactivate' }).click(); await snack(page, 'Sarah deactivated')
    await page.reload(); await ready(page)
    ok('Sarah listed under Deactivated with Reactivate', /Sarah/.test(await page.getByTestId('members-inactive').innerText()) && (await page.getByTestId('members-inactive').getByRole('button', { name: 'Reactivate' }).count()) === 1)
    ok('her own settings stay for Reactivate', sql(`select coalesce(manager_id, 'none') || '|' || accepting_leads from members where id='sarah'`) === 'james|1')
    await shot('03-deactivated')
    await page.goto(`${BASE}/leads/${lead}`); await ready(page)
    ok('her lead still carries her name', /Sarah/.test(await page.locator('main, body').first().innerText()))
    await page.goto(`${BASE}/leads/${other}`); await ready(page)
    await page.getByRole('button', { name: 'Assign Member' }).first().click(); await page.waitForTimeout(500)
    const listed = await page.getByRole('checkbox', { name: /^Assign / }).evaluateAll((els) => els.map((e) => e.getAttribute('aria-label')))
    ok('the Assign picker no longer offers her', listed.length > 0 && !listed.some((l) => /Sarah/.test(l)), listed.join(', '))
    await page.keyboard.press('Escape')
    await page.goto(`${BASE}/settings?section=studio`); await ready(page)
    ok('Settings › Studio names her as deactivated', /Sarah/.test(await page.getByTestId('team-deactivated').innerText()) && !/Sarah/.test(await page.getByTestId('team-designer').innerText()))
    await page.goto(`${BASE}/company/members`); await ready(page)
    await page.getByTestId('members-inactive').getByRole('button', { name: 'Reactivate' }).click(); await snack(page, 'Sarah reactivated')
    ok('reactivated', sql(`select is_active from members where id='sarah'`) === '1')
  })

  await step('the Owner rules, as an Admin', async () => {
    sql(`update members set role='Admin' where id='germaine'`); as('germaine')
    await page.goto(`${BASE}/company/members`); await ready(page)
    ok('an Admin cannot change the Owner’s role', await row(page, 'Dane').getByTestId('member-role').locator('button, input').first().isDisabled())
    ok('nor their own', await row(page, 'Germaine').getByTestId('member-role').locator('button, input').first().isDisabled())
    ok('nor deactivate the Owner', await row(page, 'Dane').getByRole('button', { name: 'Deactivate' }).isDisabled())
    await page.getByRole('button', { name: 'Add member' }).click()
    const dlg = page.getByRole('dialog', { name: 'Add member' })
    await dlg.getByRole('combobox', { name: 'Role' }).click(); await page.waitForTimeout(300)
    const opts = await page.getByRole('option').allInnerTexts(); await page.keyboard.press('Escape')
    ok('Add member never offers Owner to an Admin', opts.length > 0 && !opts.some((o) => /^Owner$/i.test(o.trim())), opts.join(','))
    await page.keyboard.press('Escape')
    await shot('04-admin-owner-rules')
    as('dane')
    await page.goto(`${BASE}/company/members`); await ready(page)
    ok('the Owner cannot change their own role', await row(page, 'Dane').getByTestId('member-role').locator('button, input').first().isDisabled())
    ok('and is never offered Deactivate on themself', (await row(page, 'Dane').getByRole('button', { name: 'Deactivate' }).count()) === 0)
    await page.goto(`${BASE}/settings?section=studio`); await ready(page)
    ok('Who may do what: only an Owner makes an Owner', JSON.stringify(await page.getByTestId('may-owner').locator('[data-reach]').evaluateAll((els) => els.map((e) => e.getAttribute('data-reach')))) === '["yes","no","no","no"]')
    sql(`update members set role='Designer' where id='germaine'`)
  })

  await step('a Designer reads what Owners and Admins change', async () => {
    as('alex')
    await page.goto(`${BASE}/settings?section=notifications`); await page.getByTestId('settings-notifications').waitFor(); await ready(page)
    ok('Notifications: the read-only line', (await page.getByTestId('read-only-line').count()) === 1)
    ok('Notifications: switches disabled, no Edit', await page.getByTestId('event-new_lead').locator('input[type="checkbox"]').first().isDisabled() && (await page.getByRole('button', { name: 'Edit' }).count()) === 0)
    await shot('05-designer-notifications')
    await page.goto(`${BASE}/company/profile`); await page.getByTestId('profile').waitFor(); await ready(page)
    ok('Profile: read-only, no Save changes', (await page.getByTestId('read-only-line').count()) === 1 && (await page.getByRole('button', { name: 'Save changes' }).count()) === 0 && await page.getByLabel('Company name').isDisabled())
    await shot('06-designer-profile')
    await page.goto(`${BASE}/company/templates/brand`); await ready(page)
    ok('Brand kit: read-only, no Save changes', (await page.getByTestId('read-only-line').count()) === 1 && (await page.getByRole('button', { name: 'Save changes' }).count()) === 0)
    await page.goto(`${BASE}/company/templates/quotes`); await ready(page)
    await page.getByRole('button', { name: /^More options for / }).first().click({ force: true }); await page.waitForTimeout(400)
    const items = await page.getByRole('menuitem').evaluateAll((els) => els.map((e) => `${e.textContent?.trim()}:${e.getAttribute('aria-disabled') ?? e.hasAttribute('disabled')}`))
    ok('a quote template’s default, rename and delete are refused in the menu', ['Set as default', 'Rename', 'Delete'].every((l) => items.some((i) => i.startsWith(`${l}:`) && /true/.test(i))), items.join(' · '))
    await shot('07-designer-template-menu')
    await page.keyboard.press('Escape')
    await page.goto(`${BASE}/company/integrations`); await ready(page)
    ok('Integrations: no connect or simulate', (await page.getByRole('button', { name: /Connect a Facebook page|Simulate/ }).count()) === 0)
  })

  await step('More › Company on a phone', async () => {
    const c = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
    const p = await c.newPage(); p.setDefaultTimeout(12000)
    await p.goto(`${BASE}/leads`); await ready(p)
    await p.locator('nav[aria-label="Primary"]').getByRole('button', { name: 'More' }).click(); await p.waitForTimeout(400)
    await p.getByRole('dialog', { name: 'More' }).getByRole('button', { name: 'Company' }).click(); await p.waitForTimeout(600)
    ok('the Company panel opens as a sheet', (await p.getByRole('menu', { name: 'Company' }).count()) >= 1)
    await shot('08-phone-company-sheet', p)
    await p.getByRole('menu', { name: 'Company' }).getByText('Members', { exact: true }).click()
    await p.waitForURL(/\/company\/members/); await ready(p)
    ok('Members is reachable on a phone', true)
    await shot('09-phone-members', p)
    const over = await p.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)
    ok('Members fits the phone', over <= 0, `${over}px over`)
    await c.close()
  })

  await browser.close()
  const passed = results.filter((r) => r.pass).length
  console.log(`\n${passed}/${results.length} passed`)
})()
