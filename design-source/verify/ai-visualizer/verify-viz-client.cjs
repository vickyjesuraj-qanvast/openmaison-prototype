/* AI Visualizer probe, everything around the editor (REG-675 · 676 · 677): the client's link and what it tells the studio, Company ›
   Materials, the lead's Files and Activity, the bell, a new personal design from a sample room, the phone. Against :3011 on a scratch copy.
   Usage: B=http://localhost:3011 OUT=<dir> DB=<scratch db path> NODE_PATH=$PWD/node_modules node design-source/verify/ai-visualizer/verify-viz-client.cjs */
const { chromium } = require('playwright')
const { execSync } = require('child_process')
const B = process.env.B || 'http://localhost:3011', OUT = process.env.OUT || __dirname, DB = process.env.DB
const LEAD = '1f12cbd1-b09b-47f4-89e4-454a1a5e333b', DESIGN = 'b46000d1-1638-4c7c-af20-bebbcc3b9744', TOKEN = '17fe84ab2eca47'
const sql = (q) => execSync(`sqlite3 "${DB}" "${q.replace(/"/g, '\\"')}"`).toString().trim()
let pass = 0, fail = 0
const check = (label, ok, extra = '') => { if (ok) { pass++; console.log('  ok  ', label) } else { fail++; console.log('  FAIL', label, extra) } }
;(async () => {
  const browser = await chromium.launch()
  let ctx = await browser.newContext({ viewport: { width: 1440, height: 1024 } })
  let page = await ctx.newPage()
  const errors = []
  page.on('pageerror', (e) => errors.push(e.message))
  const shot = (n) => page.screenshot({ path: `${OUT}/${n}.png`, fullPage: n.includes('share') })

  console.log('1 · the client’s link')
  // The demo's link was sent two days before the repair ran and lasts a week (R61); as the calendar passes it the link expires, so the
  // scratch copy keeps it open from today — the probe is about what an open link does
  sql(`update render_share_links set expires_at = strftime('%s','now') + 5 * 86400 where token='${TOKEN}' and expires_at < strftime('%s','now') + 86400`)
  const views0 = Number(sql(`select view_count from render_share_links where token='${TOKEN}'`))
  await page.goto(`${B}/renders/${TOKEN}`); await page.waitForTimeout(1500)
  check('the letterhead and the studio’s note', (await page.getByText('Hi Kevin, three ideas from our meeting', { exact: false }).count()) === 1)
  check('three designs, each with before and after', (await page.getByTestId('render-share-version').count()) === 3)
  check('Kevin’s favourite is marked', (await page.getByText(/Your favourite/).count()) >= 1)
  check('the change lines read by surface', (await page.getByText('Walls', { exact: true }).count()) >= 1)
  check('opening the link counts a view', Number(sql(`select view_count from render_share_links where token='${TOKEN}'`)) === views0 + 1)
  await shot('viz-10-share-page')
  const second = page.getByTestId('render-share-version').nth(1)
  await second.getByTestId('render-share-like').click(); await page.waitForTimeout(1500)
  check('I like this one moves the favourite', (await second.getByText(/Your favourite/).count()) >= 1)
  await second.getByRole('button', { name: 'Leave a note' }).click()
  await second.locator('textarea').fill('Warmer light is lovely — can we see it with the sage walls?')
  await second.getByTestId('render-share-send-note').click(); await page.waitForTimeout(1500)
  check('the note is on the design', (await second.getByText('Warmer light is lovely', { exact: false }).count()) === 1)
  await second.getByTestId('render-share-pin').click()
  const media = await second.locator('[class*="media"]').boundingBox()
  await page.mouse.click(media.x + media.width * 0.3, media.y + media.height * 0.5); await page.waitForTimeout(400)
  await page.getByTestId('viz-pin-draft').locator('textarea').fill('Can the curtains go linen?')
  await page.getByTestId('viz-pin-save').click(); await page.waitForTimeout(1500)
  check('the client’s pin lands', Number(sql(`select count(*) from render_annotations where author_role='client' and body like 'Can the curtains%'`)) === 1)
  await page.getByTestId('render-share-call').locator('input[type="tel"]').fill('91234567')
  await page.getByTestId('render-share-callback').click(); await page.waitForTimeout(1500)
  check('Ask for a call back says who will call', await page.getByTestId('render-share-called').isVisible())
  check('…and a Follow-up task lands on the lead for its members', Number(sql(`select count(*) from lead_tasks t where t.lead_id='${LEAD}' and t.kind='Follow-up' and t.title like 'Call Kevin Ng back%' and exists (select 1 from task_assignees a where a.task_id=t.id)`)) === 1)
  check('the lead’s members hear of each answer', Number(sql(`select count(*) from notifications where kind='render_feedback' and lead_id='${LEAD}'`)) >= 9 + 4 * 3)
  await shot('viz-11-share-answered')

  console.log('2 · what the studio sees of it')
  await page.goto(`${B}/visualizer/${DESIGN}`); await page.waitForTimeout(2200)
  check('the favourite moved in the strip', (await page.getByTestId('viz-version').nth(3).locator('xpath=..').locator('[class*="fav"]').count()) === 1)
  await page.goto(`${B}/leads/${LEAD}/activity`); await page.waitForTimeout(1800)
  const act = await page.locator('body').innerText()
  check('Activity: the renders', act.includes('rendered V2 of “Living room”'))
  check('Activity: the link sent', act.includes('shared 3 renders with Kevin Ng on WhatsApp'))
  check('Activity: the favourite', act.includes('as the favourite'))
  check('Activity: the call back', act.includes('asked for a call back about the renders'))
  await shot('viz-12-activity')

  console.log('3 · the lead’s Files: renders kept, a site photo opens as its room')
  await page.goto(`${B}/leads/${LEAD}/files`); await page.waitForTimeout(1800)
  check('Files › Renders holds what went to the client', (await page.getByText('Renders', { exact: true }).count()) >= 1)
  const site = sql(`select id from lead_files where lead_id='${LEAD}' and name='Master bedroom.jpg'`)
  await page.goto(`${B}/leads/${LEAD}/files/${site}`); await page.waitForTimeout(1800)
  await page.getByRole('button', { name: 'More options' }).click(); await page.waitForTimeout(300)
  await page.getByRole('menuitem', { name: 'Open in AI Visualizer' }).click()
  await page.waitForURL(/\/visualizer\//, { timeout: 15000 }); await page.waitForTimeout(2200)
  check('the photo opens as its own room', ((await page.getByTestId('viz-rooms').getByRole('radio', { checked: true }).textContent()) ?? '').includes('Master bedroom'))
  check('…and Back returns to the file', (page.url().includes('from=%2Fleads%2F') && page.url().includes('files')))

  console.log('4 · a new design from a sample room')
  await page.goto(`${B}/visualizer`); await page.waitForTimeout(1500)
  await page.getByRole('button', { name: 'New', exact: true }).click(); await page.waitForTimeout(300)
  await page.getByRole('menuitem', { name: /Blank design/ }).click()
  await page.waitForURL(/\/visualizer\/[0-9a-f-]+/, { timeout: 15000 }); await page.waitForTimeout(1800)
  check('a blank design opens on the add-room choices', await page.getByTestId('viz-empty').isVisible())
  await shot('viz-13-empty')
  await page.getByTestId('viz-sample').filter({ hasText: 'Kitchen' }).first().click()
  await page.getByTestId('viz-rooms').waitFor({ timeout: 15000 }); await page.waitForTimeout(1500)
  check('the sample kitchen is a room with its surfaces marked', (await page.getByTestId('viz-marker').count()) >= 3)

  console.log('5 · Company › Materials')
  await page.goto(`${B}/company/materials`); await page.waitForTimeout(1500)
  check('four studio materials (one in Floors)', (await page.getByTestId('library-card').count()) === 3 && (await page.getByText('Floors').count()) >= 1)
  // REG-801 (UX audit S12): a library with one way in has one plain button — New material — not a New ▾ menu
  await page.getByRole('button', { name: 'New material', exact: true }).click(); await page.waitForTimeout(500)
  await page.getByLabel('Name').fill('Terracotta clay tile')
  await page.getByTestId('material-save').click(); await page.waitForTimeout(1500)
  check('a new material joins the library', (await page.getByTestId('library-card').filter({ hasText: 'Terracotta clay tile' }).count()) === 1)
  await shot('viz-14-materials')
  await ctx.close()

  console.log('6 · the phone and the narrow gate')
  ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  page = await ctx.newPage(); page.on('pageerror', (e) => errors.push('phone: ' + e.message))
  await page.goto(`${B}/visualizer/${DESIGN}`); await page.waitForTimeout(2200)
  check('the phone: the mode dock', await page.getByTestId('viz-mode-style').isVisible())
  await page.getByTestId('viz-mode-style').tap(); await page.waitForTimeout(600)
  check('a mode opens its tray above the dock', await page.getByTestId('viz-tray').isVisible())
  check('no sideways scroll at 390', (await page.evaluate(() => document.documentElement.scrollWidth)) <= 390)
  await page.screenshot({ path: `${OUT}/viz-15-phone.png` })
  await page.setViewportSize({ width: 320, height: 700 })
  for (const path of ['/visualizer', `/renders/${TOKEN}`, `/visualizer/${DESIGN}`, '/company/materials']) {
    await page.goto(B + path); await page.waitForTimeout(1500)
    check(`no sideways scroll at 320 · ${path.split('/')[1]}`, (await page.evaluate(() => document.documentElement.scrollWidth)) <= 320)
  }
  await ctx.close()

  console.log(errors.length ? `page errors:\n${errors.join('\n')}` : 'no page errors')
  console.log(`\n${pass} passed · ${fail} failed`)
  await browser.close()
  process.exit(fail || errors.length ? 1 : 0)
})()
