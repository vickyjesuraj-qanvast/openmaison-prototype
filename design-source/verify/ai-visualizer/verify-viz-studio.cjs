/* AI Visualizer probe, the studio's side (REG-673 · 674 · 675), at 1440×1024 against :3011 on a scratch copy of the baseline.
   Usage: B=http://localhost:3011 OUT=<dir> NODE_PATH=$PWD/node_modules node design-source/verify/ai-visualizer/verify-viz-studio.cjs */
/* (pending modules S43C, a deliberate change of this rule) the AI Visualizer's living room is the owner's photo (1.0's 4a51f3522): its walls are
   'Cream Painted Side Wall' · 'Cream Painted Back Wall' · 'Cream Painted TV Wall', its sofa 'Cream Bouclé Sofa' (were 'White Painted Back Wall', 'Grey Fabric Sofa'). */
const { chromium } = require('playwright')
const B = process.env.B || 'http://localhost:3011', OUT = process.env.OUT || __dirname
const LEAD = '1f12cbd1-b09b-47f4-89e4-454a1a5e333b'
let pass = 0, fail = 0
const check = (label, ok, extra = '') => { if (ok) { pass++; console.log('  ok  ', label) } else { fail++; console.log('  FAIL', label, extra) } }
;(async () => {
  const browser = await chromium.launch()
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 1024 } })
  const page = await ctx.newPage()
  const errors = []
  page.on('pageerror', (e) => errors.push(e.message))
  const shot = (n) => page.screenshot({ path: `${OUT}/${n}.png` })

  console.log('1 · the landing and the ways in')
  await page.goto(`${B}/visualizer`); await page.waitForTimeout(1500)
  check('landing titled AI Visualizer', (await page.locator('h1').first().textContent())?.trim() === 'AI Visualizer')
  check('the bar reads its contents, not the title again', await page.getByRole('heading', { name: 'All designs' }).isVisible())
  check('Kevin Ng’s design is a card', await page.getByTestId('library-card').filter({ hasText: 'Kevin Ng' }).count() === 1)
  check('the Showroom ideas folder holds its design', (await page.getByText('Showroom ideas').count()) > 0)
  await shot('viz-01-landing')
  await page.goto(`${B}/leads/${LEAD}`); await page.waitForTimeout(1800)
  await page.getByRole('button', { name: 'AI Visualizer' }).first().click()
  await page.waitForURL(/\/visualizer\/[0-9a-f-]+/, { timeout: 15000 }); await page.waitForTimeout(1800)
  const url = page.url()
  check('the lead’s quick link opens the lead’s design', /\/visualizer\/b46000d1/.test(url), url)
  check('…carrying where it came from', url.includes('from=%2Fleads%2F'))
  await page.getByRole('button', { name: /^Back to Kevin Ng/ }).click(); await page.waitForURL(new RegExp(`/leads/${LEAD}`), { timeout: 15000 })
  check('Back returns to the lead', page.url().includes(`/leads/${LEAD}`))

  console.log('2 · the editor as it opens')
  await page.goto(`${B}/visualizer/b46000d1-1638-4c7c-af20-bebbcc3b9744`); await page.waitForTimeout(2200)
  check('three rooms as chips', (await page.getByTestId('viz-rooms').getByRole('radio').count()) === 3)
  check('the newest version is on the canvas', ((await page.getByTestId('viz-stage-chip').textContent()) ?? '').startsWith('V3'))
  check('the strip: the Original and three versions', (await page.getByTestId('viz-version').count()) === 4)
  check('the client’s favourite shows on V2', (await page.getByTestId('viz-version').nth(2).locator('xpath=..').getByText('', { exact: false }).count()) > 0)
  check('the first-visit tip', await page.getByTestId('viz-hint').isVisible())
  await page.getByRole('button', { name: 'Got it' }).click()
  check('Got it hides the tip', (await page.getByTestId('viz-hint').count()) === 0)
  await shot('viz-02-editor')

  console.log('3 · a square picks its group; a finish; Generate')
  await page.getByTestId('viz-version').first().click(); await page.waitForTimeout(600)
  check('the Original on screen', ((await page.getByTestId('viz-stage-chip').textContent()) ?? '').startsWith('Original'))
  const wall = page.getByTestId('viz-marker').filter({ has: page.locator('xpath=self::*[@aria-label="Cream Painted Side Wall"]') })
  await page.getByRole('button', { name: 'Cream Painted Side Wall' }).click(); await page.waitForTimeout(1200)
  check('the square opens the walls (all of them)', ((await page.getByTestId('viz-picker').locator('h2').textContent()) ?? '') === 'Walls')
  check('…with one tap to narrow to one wall', (await page.getByTestId('viz-scope').getByRole('radio').count()) === 4)   // (pending modules S43C, a deliberate change) All + the owner's living room's three walls
  check('the region is lit on the photo', await page.getByTestId('viz-highlight').isVisible())
  await shot('viz-03-picker')
  await page.getByTestId('viz-swatch').filter({ hasText: 'Cool Grey' }).first().click(); await page.waitForTimeout(300)
  check('the change is listed', ((await page.getByTestId('viz-changes').textContent()) ?? '').includes('Walls → Cool Grey'))
  check('Generate waits no more', await page.getByTestId('viz-generate').isEnabled())
  check('versions and quality fold into one line', ((await page.getByTestId('viz-options').textContent()) ?? '').includes('Makes 1 version · Fast'))
  await page.keyboard.press('Meta+z'); await page.waitForTimeout(300)
  check('⌘Z takes the pick back', (await page.getByTestId('viz-changes').count()) === 0)
  await page.keyboard.press('Meta+Shift+z'); await page.waitForTimeout(300)
  check('⇧⌘Z puts it back', (await page.getByTestId('viz-changes').count()) === 1)
  await page.getByTestId('viz-generate').click(); await page.waitForTimeout(500)
  check('the progress card while it renders', await page.getByTestId('viz-running').isVisible())
  await page.getByTestId('viz-running').waitFor({ state: 'visible', timeout: 5000 }).catch(() => {}); await page.getByTestId('viz-running').waitFor({ state: 'detached', timeout: 40000 }); await page.waitForTimeout(900)   // the run first shows, then ends (a slower machine started it late)
  check('V4 is on the canvas', ((await page.getByTestId('viz-stage-chip').textContent()) ?? '').startsWith('V4'))
  check('…and in the strip', (await page.getByTestId('viz-version').count()) === 5)
  check('the picks are spent', (await page.getByTestId('viz-changes').count()) === 0)
  await shot('viz-04-generated')
  await page.getByTestId('viz-compare-toggle').click(); await page.waitForTimeout(700)
  check('Compare lays the parent under a slider', await page.getByTestId('viz-compare').isVisible())
  await shot('viz-05-compare')
  await page.getByTestId('viz-compare-toggle').click()

  console.log('4 · lighting previewed live; a style; Present')
  await page.getByTestId('viz-mode-lighting').click(); await page.waitForTimeout(400)
  await page.getByTestId('viz-light-card').first().click(); await page.waitForTimeout(1500)
  check('the light previews on the photo before Generate', await page.getByTestId('viz-preview').isVisible())
  check('Generate says Relight', ((await page.getByTestId('viz-generate').textContent()) ?? '').includes('Relight'))
  await shot('viz-06-lighting')
  await page.getByTestId('viz-light-card').first().click(); await page.waitForTimeout(300)
  await page.getByTestId('viz-mode-style').click(); await page.waitForTimeout(400)
  await page.getByTestId('viz-style-card').filter({ hasText: 'Japandi' }).click(); await page.waitForTimeout(300)
  check('Generate says Restyle as Japandi', ((await page.getByTestId('viz-generate').textContent()) ?? '').includes('Restyle as Japandi'))
  await page.getByTestId('viz-style-card').filter({ hasText: 'Japandi' }).click(); await page.waitForTimeout(200)
  await page.getByTestId('viz-present-open').click(); await page.waitForTimeout(800)
  check('Present opens the version large', await page.getByTestId('viz-present').isVisible())
  await page.keyboard.press('Escape'); await page.waitForTimeout(400)

  console.log('5 · furniture: take the sofa out')
  await page.getByTestId('viz-version').first().click(); await page.waitForTimeout(500)
  await page.getByTestId('viz-mode-furniture').click(); await page.waitForTimeout(400)
  await page.getByTestId('viz-furniture-row').filter({ hasText: 'Cream Bouclé Sofa' }).click(); await page.waitForTimeout(700)
  await page.getByTestId('viz-furniture-actions').getByRole('radio', { name: 'Remove' }).click(); await page.waitForTimeout(300)
  await page.getByTestId('viz-generate').click()
  await page.getByTestId('viz-running').waitFor({ state: 'visible', timeout: 5000 }).catch(() => {}); await page.getByTestId('viz-running').waitFor({ state: 'detached', timeout: 40000 }); await page.waitForTimeout(900)   // the run first shows, then ends (a slower machine started it late)
  /* (audit 2026-09-26, F2) a version names a piece by its kind, and a removal says so: "V5 · Sofa taken out" */
  check('V5 takes the sofa out', ((await page.getByTestId('viz-stage-chip').textContent()) ?? '').includes('Sofa taken out'))
  await shot('viz-07-removed')

  console.log('6 · a pin, then Share with client')
  await page.getByTestId('viz-pin-toggle').click()
  const frame = await page.getByTestId('viz-frame').boundingBox()
  await page.mouse.click(frame.x + frame.width * 0.55, frame.y + frame.height * 0.3); await page.waitForTimeout(400)
  await page.getByTestId('viz-pin-draft').locator('textarea').fill('Could this wall take the sage instead?')
  await page.getByTestId('viz-pin-save').click(); await page.waitForTimeout(1500)
  check('the pin lands on the version', (await page.getByTestId('viz-pin').count()) === 1)
  check('its thread opens', await page.getByTestId('viz-pin-thread').isVisible())
  await shot('viz-08-pin')
  await page.getByTestId('viz-pin-toggle').click()
  await page.getByTestId('viz-share').click(); await page.waitForTimeout(700)
  check('Share picks the version on screen', (await page.getByTestId('viz-share-pick').and(page.locator('[aria-pressed="true"]')).count()) === 1)
  check('…and lists the link sent before', await page.getByTestId('viz-shared-before').isVisible())
  await page.getByTestId('viz-share-pick').nth(1).click()
  await page.getByTestId('viz-create-link').click(); await page.waitForTimeout(1500)
  const link = (await page.getByTestId('viz-share-url').textContent()) ?? ''
  check('a link is made', /\/renders\/[A-Za-z0-9_-]+$/.test(link), link)
  await shot('viz-09-share')
  await page.keyboard.press('Escape'); await page.waitForTimeout(600)

  console.log(errors.length ? `page errors:\n${errors.join('\n')}` : 'no page errors')
  console.log(`\n${pass} passed · ${fail} failed`)
  await browser.close()
  process.exit(fail || errors.length ? 1 : 0)
})()
